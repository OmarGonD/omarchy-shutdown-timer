function language(locale) {
    var code = String(locale || "").toLowerCase().split(/[_.:@-]/)[0];
    return messages[code] ? code : "en";
}
function tr(locale, key, args) {
    var lang = language(locale);
    var value = messages[lang][key] || messages.en[key] || key;
    (args || []).forEach(function(arg, i) { value = value.split("%" + (i + 1)).join(String(arg)); });
    return value;
}
